CREATE TABLE TRANSACCIONES_PROCESADAS (
                                          ID NUMBER PRIMARY KEY,
                                          FECHA DATE NOT NULL,
                                          MONTO NUMBER(15,2) NOT NULL,
                                          TIPO VARCHAR2(50) NOT NULL,
                                          ESTADO VARCHAR2(30) NOT NULL
);

CREATE TABLE INTERESES_PROCESADOS (
                                      CUENTA_ID NUMBER PRIMARY KEY,
                                      NOMBRE VARCHAR2(150) NOT NULL,
                                      SALDO_INICIAL NUMBER(15,2) NOT NULL,
                                      EDAD NUMBER,
                                      TIPO VARCHAR2(50) NOT NULL,
                                      INTERES_CALCULADO NUMBER(15,2) NOT NULL,
                                      SALDO_FINAL NUMBER(15,2) NOT NULL,
                                      ESTADO VARCHAR2(30) NOT NULL
);

CREATE TABLE CUENTAS_ANUALES_PROCESADAS (
                                            REGISTRO_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            CUENTA_ID NUMBER NOT NULL,
                                            FECHA DATE NOT NULL,
                                            TRANSACCION VARCHAR2(50) NOT NULL,
                                            MONTO NUMBER(15,2) NOT NULL,
                                            DESCRIPCION VARCHAR2(255),
                                            ESTADO VARCHAR2(30) NOT NULL
);